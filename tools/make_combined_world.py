#!/usr/bin/env python3
"""
Generate the connected mapper test arena (combined_rooms.world).

Rooms use the room shape classifier's sizes and form a tree, joined by short
corridors. Every passage has an ArUco tile on the corridor floor and the start
room has its own start tile, so the mapper sees one tag per crossing.

    python3 tools/make_combined_world.py > src/inventory/src/worlds/combined_rooms.world
"""

import math

WALL = 0.05        # wall thickness (m)
HEIGHT = 0.5       # wall height (m)
DOOR = 0.35        # corridor / doorway width (m)

# Interior polygons, counter-clockwise. Each edge index can carry one doorway.
ROOMS = {
    # name: (polygon, {edge index: doorway centre along the edge (0..1)})
    'small_square': ([(-1.0, 0.15), (-0.4, 0.15), (-0.4, 0.75), (-1.0, 0.75)], {1: 0.5}),
    'large_square': ([(0.0, 0.0), (0.9, 0.0), (0.9, 0.9), (0.0, 0.9)],
                     {1: 0.5, 2: 0.5, 3: 0.5}),
    'rectangle': ([(0.0, 1.3), (0.9, 1.3), (0.9, 1.8), (0.0, 1.8)], {0: 0.5}),
    'hallway': ([(1.3, 0.225), (2.5, 0.225), (2.5, 0.675), (1.3, 0.675)], {1: 0.5, 3: 0.5}),
    'triangle': ([(2.9, 0.05), (2.9 + 0.8 * math.sqrt(3) / 2, 0.45), (2.9, 0.85)], {2: 0.5}),
}

# Corridors: (start, end) of the centre line, from one doorway to the other.
CORRIDORS = [
    ((-0.4, 0.45), (0.0, 0.45)),    # small square - large square
    ((0.45, 0.9), (0.45, 1.3)),     # large square - rectangle
    ((0.9, 0.45), (1.3, 0.45)),     # large square - hallway
    ((2.5, 0.45), (2.9, 0.45)),     # hallway - triangle
]

# (marker id, x, y, comment)
TAGS = [
    (34, -0.7, 0.45, 'start tile, small square'),
    (4, -0.2, 0.45, 'passage small square - large square'),
    (20, 0.45, 1.1, 'passage large square - rectangle'),
    (49, 1.1, 0.45, 'passage large square - hallway'),
    (23, 2.7, 0.45, 'passage hallway - triangle'),
]

COLOUR = ('<material><ambient>0.25 0.45 0.85 1</ambient>'
          '<diffuse>0.30 0.55 0.95 1</diffuse></material>')

links = []


def wall(name, x0, y0, x1, y1, extend=0.0):
    """Add a wall box whose inner face runs from (x0, y0) to (x1, y1)."""
    length = math.hypot(x1 - x0, y1 - y0)
    if length < 1e-6:
        return
    ux, uy = (x1 - x0) / length, (y1 - y0) / length
    # Push the box outwards (right of travel for a CCW polygon) by half a wall.
    cx = (x0 + x1) / 2 + uy * WALL / 2
    cy = (y0 + y1) / 2 - ux * WALL / 2
    yaw = math.atan2(uy, ux)
    size = f'{length + 2 * extend:.4f} {WALL} {HEIGHT}'
    links.append(
        f'      <link name="{name}">\n'
        f'        <pose>{cx:.4f} {cy:.4f} {HEIGHT / 2} 0 0 {yaw:.6f}</pose>\n'
        f'        <collision name="collision"><geometry><box><size>{size}</size>'
        f'</box></geometry></collision>\n'
        f'        <visual name="visual"><geometry><box><size>{size}</size>'
        f'</box></geometry>{COLOUR}</visual>\n'
        f'      </link>')


for room, (polygon, doors) in ROOMS.items():
    for index, (start, end) in enumerate(zip(polygon, polygon[1:] + polygon[:1])):
        name = f'{room}_{index}'
        # Rectangles get their corners closed by extending each wall.
        extend = WALL if len(polygon) == 4 else WALL * 1.8
        if index not in doors:
            wall(name, *start, *end, extend=extend)
            continue
        length = math.hypot(end[0] - start[0], end[1] - start[1])
        t0 = doors[index] - DOOR / 2 / length
        t1 = doors[index] + DOOR / 2 / length

        def point(t, s=start, e=end):
            return (s[0] + (e[0] - s[0]) * t, s[1] + (e[1] - s[1]) * t)
        # Only the outer end of each piece is extended, so the doorway stays clear.
        a, b = point(t0), point(t1)
        ux, uy = (end[0] - start[0]) / length, (end[1] - start[1]) / length
        wall(name + 'a', start[0] - ux * extend, start[1] - uy * extend, *a)
        wall(name + 'b', *b, end[0] + ux * extend, end[1] + uy * extend)

for index, ((x0, y0), (x1, y1)) in enumerate(CORRIDORS):
    length = math.hypot(x1 - x0, y1 - y0)
    ux, uy = (x1 - x0) / length, (y1 - y0) / length
    # Side walls sit DOOR/2 either side of the centre line, spanning the gap
    # between the two rooms' wall faces.
    nx, ny = -uy * DOOR / 2, ux * DOOR / 2
    sx, sy = x0 + ux * WALL, y0 + uy * WALL
    ex, ey = x1 - ux * WALL, y1 - uy * WALL
    wall(f'corridor_{index}_left', ex + nx, ey + ny, sx + nx, sy + ny)
    wall(f'corridor_{index}_right', sx - nx, sy - ny, ex - nx, ey - ny)

tags = '\n'.join(
    f'    <!-- {comment} -->\n'
    f'    <include><uri>model://aruco_marker_{tag}</uri><name>tag_{tag}</name>'
    f'<pose>{x} {y} 0 0 0 0</pose></include>'
    for tag, x, y, comment in TAGS)

print(f'''<?xml version="1.0"?>
<!--
  Connected mapper test arena, generated by tools/make_combined_world.py.
  Rooms use the room shape classifier sizes and form a tree:
    small square (start) -4- large square -20- rectangle
                             large square -49- hallway -23- triangle
  Each number is the ArUco tile on that passage's corridor floor. Tile 34 is
  the start tile in the small square. Spawn the robot at (-0.7, 0.45).
-->
<sdf version="1.9">
  <world name="combined_rooms">
    <physics name="room_physics" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <gravity>0 0 -9.8</gravity>
    <scene>
      <ambient>0.7 0.7 0.7 1</ambient>
      <background>0.8 0.85 0.9 1</background>
      <shadows>true</shadows>
    </scene>
    <light type="directional" name="sun">
      <pose>1.5 0.9 5 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.2 -0.9</direction>
    </light>

    <model name="ground">
      <static>true</static>
      <link name="ground_link">
        <pose>1.3 0.9 -0.025 0 0 0</pose>
        <collision name="ground_collision">
          <geometry><box><size>6.0 3.5 0.05</size></box></geometry>
        </collision>
        <visual name="ground_visual">
          <geometry><box><size>6.0 3.5 0.05</size></box></geometry>
          <material>
            <ambient>0.5 0.5 0.5 1</ambient>
            <diffuse>0.62 0.62 0.62 1</diffuse>
          </material>
        </visual>
      </link>
    </model>

    <model name="connected_room_walls">
      <static>true</static>
{chr(10).join(links)}
    </model>

    <!-- ArUco floor tiles (DICT_4X4_50), installed with the inventory package. -->
{tags}
  </world>
</sdf>''')
